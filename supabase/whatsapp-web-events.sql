-- Isolated event inbox for the Encontre Mais WhatsApp Web connector.
-- Review and apply manually in the existing external Supabase project.
create table if not exists public.whatsapp_web_events (
  id bigint generated by default as identity primary key,
  provider text not null default 'baileys_whatsapp_web',
  event_type text not null,
  external_event_id text not null unique,
  payload jsonb not null,
  received_at timestamptz not null default now(),
  processing_status text not null default 'received'
    check (processing_status in ('received','processing','processed','ignored','failed')),
  processed_at timestamptz,
  processing_error text
);
create index if not exists whatsapp_web_events_status_received_idx
  on public.whatsapp_web_events(processing_status, received_at);
alter table public.whatsapp_web_events enable row level security;
-- No anon/authenticated policies: service-role access only.
grant select, insert, update, delete on public.whatsapp_web_events to service_role;
grant usage, select on sequence public.whatsapp_web_events_id_seq to service_role;
